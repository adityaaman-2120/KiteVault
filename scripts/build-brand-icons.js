#!/usr/bin/env node
// Builds the offline brand icons from scripts/brand-list.js. Run it by hand when the list changes;
// the result (PNG files and two TypeScript tables) is committed, so building the app needs none of
// the tools below, and the app itself makes no network request for icons.
//
//   BRAND_TOOLS=<folder that has node_modules/simple-icons and node_modules/@resvg/resvg-js> \
//     node scripts/build-brand-icons.js
//
// Glyphs come from Simple Icons (CC0, https://simpleicons.org). They are drawn white on a
// transparent background; the app puts them on a tile in the brand's colour and tints them dark
// when that colour is light. The logos themselves remain trademarks of their owners.

const fs = require('node:fs');
const path = require('node:path');

const tools = process.env.BRAND_TOOLS;
if (!tools) {
  console.error('Set BRAND_TOOLS to a folder that has simple-icons and @resvg/resvg-js installed.');
  process.exit(1);
}
const need = (name) => require(path.join(tools, 'node_modules', name));
const { Resvg } = need('@resvg/resvg-js');
const simpleIcons = need('simple-icons');
const iconsDir = path.join(tools, 'node_modules', 'simple-icons', 'icons');

const ROOT = path.resolve(__dirname, '..');
const OUT_IMAGES = path.join(ROOT, 'assets', 'brands');
const OUT_TABLE = path.join(ROOT, 'src', 'features', 'icons', 'brandTable.generated.ts');
const OUT_IMAGE_MAP = path.join(ROOT, 'src', 'features', 'icons', 'brandImages.generated.ts');
const SIZE = 96;

const list = require('./brand-list.js');
const bySlug = new Map(Object.values(simpleIcons).map((i) => [i.slug, i]));

const normal = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '');
const keyOf = (brand) => brand.slug || normal(brand.name);

fs.rmSync(OUT_IMAGES, { recursive: true, force: true });
fs.mkdirSync(OUT_IMAGES, { recursive: true });
fs.mkdirSync(path.dirname(OUT_TABLE), { recursive: true });

const brands = {};
const domains = {};
const packages = {};
const names = {};
const images = [];
const problems = [];

function claim(map, what, value, key) {
  if (map[value] && map[value] !== key) problems.push(`${what} "${value}" is listed for ${map[value]} and ${key}`);
  map[value] = key;
}

for (const brand of list) {
  const key = keyOf(brand);
  if (brands[key]) problems.push(`duplicate brand ${key}`);
  let hex = brand.hex;
  let glyph = false;

  if (brand.slug) {
    const icon = bySlug.get(brand.slug);
    const file = path.join(iconsDir, `${brand.slug}.svg`);
    if (!icon || !fs.existsSync(file)) {
      problems.push(`no Simple Icons glyph named "${brand.slug}" (${brand.name}); give it a hex instead`);
      continue;
    }
    hex = `#${icon.hex}`;
    const svg = fs.readFileSync(file, 'utf8').replace('<svg ', '<svg fill="#FFFFFF" ');
    const png = new Resvg(svg, { fitTo: { mode: 'width', value: SIZE } }).render().asPng();
    fs.writeFileSync(path.join(OUT_IMAGES, `${key}.png`), png);
    images.push(key);
    glyph = true;
  }
  if (!/^#[0-9A-Fa-f]{6}$/.test(hex || '')) {
    problems.push(`${brand.name} has no valid colour`);
    continue;
  }

  brands[key] = { name: brand.name, hex: hex.toUpperCase(), glyph };
  for (const d of brand.domains || []) claim(domains, 'domain', d.toLowerCase(), key);
  for (const p of brand.packages || []) claim(packages, 'package', p, key);
  // Titles are matched exactly (ignoring case, spaces and punctuation), and only when at least
  // 3 characters long, so a title such as "X" or "Mi" never picks a brand by accident.
  for (const n of [brand.name, ...(brand.aliases || [])]) {
    const k = normal(n);
    if (k.length >= 3) claim(names, 'name', k, key);
  }
}

if (problems.length) {
  console.error('Problems:\n - ' + problems.join('\n - '));
  process.exit(1);
}

const banner = '// Generated by scripts/build-brand-icons.js from scripts/brand-list.js. Do not edit by hand.\n';
const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(
  OUT_TABLE,
  `${banner}
export type BrandInfo = { name: string; hex: string; glyph: boolean };

export const BRANDS: Record<string, BrandInfo> = ${JSON.stringify(sorted(brands), null, 2)};

// Web address (a parent also covers its subdomains) -> brand.
export const BRAND_DOMAINS: Record<string, string> = ${JSON.stringify(sorted(domains), null, 2)};

// Android package name -> brand.
export const BRAND_PACKAGES: Record<string, string> = ${JSON.stringify(sorted(packages), null, 2)};

// Exact title, lower case without spaces or punctuation -> brand.
export const BRAND_NAMES: Record<string, string> = ${JSON.stringify(sorted(names), null, 2)};
`,
);
fs.writeFileSync(
  OUT_IMAGE_MAP,
  `${banner}import type { ImageSourcePropType } from 'react-native';

export const BRAND_IMAGES: Record<string, ImageSourcePropType> = {
${images
  .sort()
  .map((k) => `  '${k}': require('../../../assets/brands/${k}.png'),`)
  .join('\n')}
};
`,
);

const bytes = images.reduce((n, k) => n + fs.statSync(path.join(OUT_IMAGES, `${k}.png`)).size, 0);
console.log(
  `${Object.keys(brands).length} brands (${images.length} with a logo, ${
    Object.keys(brands).length - images.length
  } colour only), ${Object.keys(domains).length} addresses, ${Object.keys(packages).length} apps, ${(bytes / 1024).toFixed(0)} KB of images.`,
);
