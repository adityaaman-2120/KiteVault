// Builds src/features/about/licenses.generated.ts from the libraries listed under "dependencies"
// in package.json: name, version, license and the text of each library's licence file.
// Run it after adding or updating a dependency:  npm run licenses
//
// Only direct dependencies are listed. Each of them has its own dependencies under their own
// licences (mostly MIT); the About screen says so.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const LICENSE_FILE = /^(licen[sc]e|copying)(\.(md|txt|markdown))?$/i;
const MAX_TEXT = 30_000;

function licenseId(info) {
  if (typeof info.license === 'string') return info.license;
  if (info.license && typeof info.license.type === 'string') return info.license.type;
  if (Array.isArray(info.licenses)) return info.licenses.map((l) => l.type).join(' OR ');
  return 'UNKNOWN';
}

function repository(info) {
  const repo = typeof info.repository === 'string' ? info.repository : info.repository?.url;
  if (!repo) return info.homepage ?? '';
  return repo
    .replace(/^git\+/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/\.git$/, '');
}

const texts = [];
const textIndex = new Map();
const entries = [];

for (const name of Object.keys(pkg.dependencies).sort()) {
  const dir = path.join(root, 'node_modules', name);
  const info = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const file = fs.readdirSync(dir).find((f) => LICENSE_FILE.test(f));
  const text = file ? fs.readFileSync(path.join(dir, file), 'utf8').trim().slice(0, MAX_TEXT) : '';
  let index = -1;
  if (text) {
    index = textIndex.get(text) ?? -1;
    if (index === -1) {
      index = texts.push(text) - 1;
      textIndex.set(text, index);
    }
  }
  entries.push({
    name,
    version: info.version,
    license: licenseId(info),
    url: repository(info),
    text: index,
  });
}

const out = `// GENERATED by scripts/generate-licenses.js: do not edit by hand. Run "npm run licenses".
export type LicenseEntry = {
  name: string;
  version: string;
  license: string;
  url: string;
  // Index into LICENSE_TEXTS, or -1 when the library ships no licence file.
  text: number;
};

export const LICENSES: LicenseEntry[] = ${JSON.stringify(entries, null, 2)};

// Identical licence texts are stored once.
export const LICENSE_TEXTS: string[] = ${JSON.stringify(texts, null, 2)};
`;

const target = path.join(root, 'src', 'features', 'about', 'licenses.generated.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
const missing = entries.filter((e) => e.text === -1).map((e) => e.name);
console.log(`${entries.length} libraries, ${texts.length} distinct licence texts.`);
if (missing.length) console.log(`No licence file found for: ${missing.join(', ')}`);
